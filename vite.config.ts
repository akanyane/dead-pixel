import { createHash } from 'node:crypto';
import { readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

/** Lists every file under `public/`, relative to it, with forward slashes. */
function publicFiles(dir = 'public'): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? publicFiles(path) : [relative('public', path).split('\\').join('/')];
  });
}

/**
 * Writes `sw.js` at build time with the exact list of files to cache, so the game
 * works offline after the first visit. The cache name comes from a hash of that
 * list, so every release replaces the previous cache.
 */
function serviceWorker(): Plugin {
  return {
    name: 'dead-pixel-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      // duplicates would make cache.addAll() fail, so dedupe
      const files = [...new Set(['./', 'index.html', ...Object.keys(bundle), ...publicFiles()])].filter((f) => f !== 'sw.js');
      const version = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(version, files) });
    },
  };
}

function swSource(version: string, files: string[]) {
  return `// Generated by vite.config.ts. Caches the whole game for offline play.
const CACHE = 'dead-pixel-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('dead-pixel-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  // pages: network first, so a new release shows up as soon as there is a connection
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put('index.html', copy));
          return response;
        })
        .catch(() => caches.match('index.html')),
    );
    return;
  }
  // everything else has a hashed name or never changes within a release: cache first
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)));
});
`;
}

// relative paths: the build works on any static host, including subfolders
export default defineConfig({ base: './', plugins: [serviceWorker()] });
